/**
 * Import statements, per language.
 *
 * Without this, typing `import java.` offers nothing useful: the completion
 * provider reads the dot as member access and answers with *methods*, which is
 * exactly backwards. An import line is a namespace tree of its own, so it gets
 * its own catalogue and its own branch in the provider.
 *
 * `paths` holds complete names. The provider walks one segment at a time — for
 * `import java.ut` it collects every path under `java.` and offers the next
 * segment (`util`, `io`, `lang`, …) — and lets Monaco filter by what was typed.
 */
export interface ImportCatalog {
  /** Full importable names, e.g. `java.util.Scanner` or `std::io::Read`. */
  paths: string[];
  /** Regex source, anchored with `^`, matching the start of an import line. */
  trigger: string;
  /** For `from X import Y` syntax: group 1 captures the module. */
  fromTrigger?: string;
  /** Segment separator. An empty string treats each path as one atom. */
  separator?: string;
  /** Whether a path's final segment names a type rather than a package. */
  types?: boolean;
}

