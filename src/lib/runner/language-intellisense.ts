/**
 * IntelliSense for the languages Monaco ships no language worker for.
 *
 * Monaco's own workers cover TypeScript, JavaScript and JSON — real type
 * checking, hover, signature help and diagnostics. Every other language in the
 * runner (Python, C, Java, …) has a grammar for syntax highlighting but no
 * worker, so out of the box there is not a single completion.
 *
 * This module is the substitute. For each language it carries:
 *
 *   keywords    reserved words
 *   types       class and type names
 *   constants   true/false/null and other named values
 *   functions   built-ins with signatures, e.g. "range(start, stop, step)"
 *   snippets    templates with tab stops, e.g. "for … in …"
 *   members     methods offered after a `.`
 *
 * It is deliberately data, not logic — `runner-editor.tsx` turns all of it into
 * Monaco providers. Nothing here is language-server grade: it cannot resolve a
 * receiver's real type, so `members` after a `.` is the union of what the
 * language's common types offer. That is still the difference between a text box
 * and a small IDE.
 *
 * Snippet bodies use Monaco's snippet syntax: `${1:placeholder}` is a tab stop,
 * `$0` the final cursor. They are written as single-quoted strings — a template
 * literal would try to interpolate `${1:…}`.
 */

export interface Snippet {
  /** What the user types to see it, e.g. "for". */
  label: string;
  /** Template body with `${1:placeholder}` tab stops. */
  body: string;
  /** Overrides the default "snippet" detail line. */
  detail?: string;
}

export interface LanguageIntellisense {
  keywords: string[];
  types?: string[];
  constants?: string[];
  /** `"name(param, param)"` — the parenthesised part becomes the signature. */
  functions?: string[];
  snippets?: Snippet[];
  /** `"name(param)"` entries offered after a `.`. */
  members?: string[];
}

